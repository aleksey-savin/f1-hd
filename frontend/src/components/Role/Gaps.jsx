import PillPanel from "@/components/app/PillPanel";
import { usePermissionCatalogue } from "@/store/authed-user";

/**
 * Права, которых не даёт ни одна роль, кроме полного доступа.
 *
 * Смысл блока — показать дыры каталога: пока право сюда попадает, выдать его
 * можно только вместе со всем порталом. Правило считает сервер («роль отдаёт
 * весь словарь» — там же, где им зеркалится isAdmin), здесь только вёрстка.
 *
 * Вёрстка — общий `app/PillPanel`: облако пилюль, свёрнутое до трёх рядов.
 * Прежняя своя таблица «строка на право» с повторённым в каждой строке
 * «только полный доступ» на полусотне прав выросла в простыню ниже самого
 * списка ролей; у пилюль высота от числа прав почти не зависит, а причина
 * попадания в список у всех строк одна — и сказана один раз, строкой сверху.
 *
 * Пустой список означает, что каталог закрыт полностью, — тогда блока нет
 * вовсе: панель с нулём была бы шумом под каждым списком ролей.
 */
const RoleGaps = ({ gaps = [] }) => {
  const catalogue = usePermissionCatalogue();
  if (!gaps.length) return null;

  const wanted = new Set(gaps);
  // Порядок словаря: соседние права одного раздела встают рядом сами
  const items = catalogue.flatMap((group) =>
    group.actions
      .filter((action) => wanted.has(action.id))
      .map((action) => ({ _id: action.id, title: action.label })),
  );
  if (!items.length) return null;

  return (
    <PillPanel
      label="Права без своей роли"
      hint="Эти права даёт только роль с полным доступом. Чтобы выдавать их точечно — добавьте в подходящую роль."
      items={items}
    />
  );
};

export default RoleGaps;
