/**
 * Варианты поля «Инициатор» формы заявки.
 *
 * Сотруднику — люди выбранной компании плюс те, кто ведёт заявки (заявку
 * заводят и на коллегу, и на клиента); клиенту список приходит с сервера уже
 * суженным до его компании.
 *
 * НЫНЕШНИЙ ИНИЦИАТОР ЕСТЬ В ВАРИАНТАХ ВСЕГДА. Сервер отдаёт только тех, кого
 * можно выбрать заново, — без служебных учёток, отключённых и людей чужой
 * компании. А регламентные заявки заводит как раз служебная учётка
 * («Планировщик регламентных заданий», «Служба техподдержки»): значение в
 * форме было, показать его было нечем, и поле выглядело пустым — менеджеры
 * читали это как «заявка создана без инициатора». Поле обязано показывать то,
 * что в заявке лежит, даже если выбрать это заново уже нельзя.
 */
const asId = (value) => (value == null ? "" : String(value._id ?? value));

export const applicantOptions = ({
  applicants = [],
  responsibles = [],
  companyId = "",
  isEndUser = false,
  current = null,
}) => {
  // «Кто ведёт заявки» не вычитывается из прав каждого человека: с ролями в
  // документе пользователя флага нет, и такой фильтр молча выбрасывал бы
  // половину списка. Сервер уже посчитал этот набор — это и есть responsibles.
  const handlers = new Set(responsibles.map(asId));
  const list = isEndUser
    ? applicants
    : applicants.filter(
        (user) => handlers.has(asId(user)) || asId(user.company) === companyId,
      );

  // Голый идентификатор без имени показать нечем — нужен объект человека
  const known = current && typeof current === "object" && current._id;
  if (!known || list.some((user) => asId(user) === asId(current))) return list;
  return [current, ...list];
};
