/**
 * Промпт: подсказка для распознавания речи OpenAI.
 * Что делает: настраивает Whisper/gpt-4o-transcribe на аккуратную русскую
 *   пунктуацию для записей звонков ТП без добавления фактов и перевода.
 * Где используется: services/speechToTextService.js → transcribeWithOpenai
 *   (ветка без диаризации).
 * Название службы поддержки — из настроек (contacts.title); пустое опускается.
 */
module.exports = ({ supportCompany } = {}) => {
  const name = String(supportCompany || "")
    .replace(/\s+/g, " ")
    .trim();

  return `Это запись телефонного разговора службы техподдержки${name ? ` ${name}` : ""}. Расшифруй на русском языке с аккуратной пунктуацией, без добавления фактов и без перевода.`;
};
