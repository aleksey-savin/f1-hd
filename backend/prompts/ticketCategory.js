/**
 * Промпт: автоопределение категории заявки (system + user).
 * Что делает: по теме и описанию заявки просит модель выбрать одну наиболее
 *   подходящую категорию из переданного списка (опираясь на описание каждой
 *   категории) и вернуть её id; если ничего уверенно не подходит — null. Ответ JSON.
 *   При needsTitle тем же ответом просит тему заявки: заявитель на портале поля
 *   «Тема» не видит, и без модели там стоит обрезка описания.
 * Где используется: services/ticketCategoryService.js → detectTicketCategory
 *   (через aiService.generateJson).
 *
 * @param {object} params
 * @param {string} params.title тема (заголовок) заявки — учитывается наравне с
 *   описанием, особенно когда описание пустое или содержит лишь пересланную переписку
 * @param {string} params.description очищенное от HTML описание заявки
 * @param {{ id: string, title: string, description?: string }[]} params.categories
 *   активные категории-кандидаты
 * @param {boolean} [params.needsTitle] попросить модель написать тему заявки
 * @returns {{ system: string, user: string }}
 */
module.exports = ({
  title = "",
  description = "",
  categories = [],
  needsTitle = false,
}) => {
  const answerShape = needsTitle
    ? '{ "categoryId": "<id выбранной категории или null>", "closest": ["<id>", "<id>", "<id>"], "reason": "краткое обоснование на русском", "title": "тема заявки" }'
    : '{ "categoryId": "<id выбранной категории или null>", "closest": ["<id>", "<id>", "<id>"], "reason": "краткое обоснование на русском" }';

  const system = [
    "Ты — классификатор обращений в техническую поддержку.",
    "Тебе передают заявку (тема, описание) и список категорий-кандидатов, у каждой — id, название и описание.",
    "Учитывай и ТЕМУ, и ОПИСАНИЕ заявки. Тема письма часто содержит суть проблемы: если описание пустое, короткое или это просто пересланная переписка — определяй категорию по теме.",
    "Выбери ОДНУ категорию, которая лучше всего подходит к заявке, опираясь прежде всего на ОПИСАНИЕ категории (description), а название используй как подсказку.",
    "Если ни одна категория не подходит уверенно — верни categoryId со значением null. Не угадывай и не выдумывай категории вне списка.",
    "Также всегда возвращай closest — массив id до 3 наиболее близких по смыслу категорий, отсортированных по убыванию релевантности. Если categoryId определён — это следующие по близости варианты; если categoryId = null — самые близкие из возможных (чтобы человек мог выбрать вручную).",
    ...(needsTitle
      ? [
          "Дополнительно напиши ТЕМУ заявки в поле title: одна строка до 80 знаков, на русском, называющая суть проблемы словами заявителя.",
          "Тема — заголовок, а не пересказ: без приветствий, без вежливых оборотов, без точки в конце, без кавычек вокруг всей строки.",
          "Бери только то, что написано в заявке. Не добавляй причин, оборудования и обстоятельств, которых в тексте нет.",
          "Если из описания сути не видно — верни title пустой строкой; тему тогда оставят как есть.",
        ]
      : []),
    "Отвечай СТРОГО в формате JSON без какого-либо текста вокруг:",
    answerShape,
    "categoryId и все значения closest должны быть только из id переданных категорий (categoryId может быть null).",
  ].join("\n");

  const user = JSON.stringify({
    ticket: { title, description },
    categories,
  });

  return { system, user };
};
