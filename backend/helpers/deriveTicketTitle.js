const { htmlToPlainText } = require("./htmlToPlainText");

// Тема заявки, выведенная из описания, — для случаев, когда её не пишет
// человек: заявитель на портале поля «Тема» не видит, а сама тема уезжает в
// список, в письмо, в Telegram и в отчёты.
//
// Раньше это делал браузер: `htmlToPlainText(description).substring(0, 50)`.
// За год 684 из 884 клиентских заявок получили тему ровно в 50 знаков,
// оборванную посреди слова, — поэтому вывод переехал на сервер и знает про
// границы предложений.
//
// Порядок: текст целиком → первое осмысленное предложение → обрезка по границе
// слова с многоточием.

const MAX_LENGTH = 80;

// Короче этого обрывок перестаёт быть темой, поэтому граница предложения
// принимается только правее: у «Не работает.» нет предмета.
const MIN_SENTENCE = 20;

// Приветствие темой не бывает, а начинается с него добрая половина писем и
// заявок с портала. Снимаем только ведущее и только если после него что-то
// осталось.
const GREETING =
  /^(?:добр(?:ый|ое|ого)\s+(?:день|вечер|утро|времени\s+суток)|здравствуйте|здравствуй|приветствую|привет|коллеги|уважаемые\s+коллеги)[\s,!.;:—–-]*/iu;

// Хвостовая пунктуация: тема — заголовок, а не фраза, точка в конце ей не нужна
const trimTail = (text) => text.replace(/[\s.,;:—–-]+$/u, "");

// htmlToPlainText меняет каждый тег на пробел, поэтому «<span>(</span>Единая»
// превращается в «( Единая». Возвращаем пунктуацию на место — тему читают в
// списке, и лишний пробел там виден.
const tidySpaces = (text) =>
  text.replace(/\s+([)\],.;:!?»])/gu, "$1").replace(/([(\[«])\s+/gu, "$1");

/**
 * Вывести тему заявки из её описания.
 *
 * @param {string} description описание (html или простой текст)
 * @param {number} [maxLength] предельная длина темы
 * @returns {string} тема или пустая строка, если из описания нечего взять
 */
const deriveTicketTitle = (description = "", maxLength = MAX_LENGTH) => {
  const plain = htmlToPlainText(description);
  if (!plain) return "";

  const withoutGreeting = plain.replace(GREETING, "");
  const text = tidySpaces(withoutGreeting.trim() || plain);

  // Тема — первое предложение, даже если весь текст влезал в лимит: «Не работает
  // звук на компьютере. Посмотрите, пожалуйста, причину» как заголовок списка
  // читается хуже, чем первая его половина.
  //
  // Конец предложения — знак препинания и следом заглавная буква. Пробел между
  // ними необязателен: в живых заявках сплошь и рядом «…установить фамилию.Когда
  // звоню…». Слово перед знаком обязано быть длиннее двух букв, иначе границей
  // считались бы «т. д.», «см.» и инициалы «И. И. Иванов».
  const sentenceEnd = /(?<=\p{L}{3})[.!?…]\s*(?=[А-ЯЁA-Z])/gu;
  const head = text.slice(0, maxLength + 1);
  let match;
  while ((match = sentenceEnd.exec(head)) !== null) {
    const cut = match.index + 1;
    // Первая подходящая граница, а не последняя: тема — первое предложение,
    // а не столько предложений, сколько влезло в лимит
    if (cut >= MIN_SENTENCE) return trimTail(text.slice(0, cut));
  }

  if (text.length <= maxLength) return trimTail(text);

  // Многоточие входит в лимит, а не прибавляется к нему
  const clipped = text.slice(0, maxLength - 1);
  const lastSpace = clipped.lastIndexOf(" ");
  const body = lastSpace > MIN_SENTENCE ? clipped.slice(0, lastSpace) : clipped;
  return `${trimTail(body)}…`;
};

module.exports = { deriveTicketTitle, MAX_TITLE_LENGTH: MAX_LENGTH };
