const User = require("@/models/user");

/**
 * Отключение учётной записи со сроком.
 *
 * `banExpires` — дата, ПОСЛЕ которой отключение не действует. Плагин `admin`
 * снимает просроченное отключение сам, но только в своём хуке на создание
 * сеанса — а до него наши гейты не доходят: вход, ссылка из письма, ссылка
 * подмены и телеграм-актор отказывают по `banned` раньше. Так «отключить до
 * понедельника» оказывалось «отключить, пока администратор не включит руками».
 *
 * Поэтому правило «вышедший срок — не отключение» живёт здесь, и всякая
 * проверка доступа обязана спрашивать `isBanned(user)`, а не читать
 * `user.banned`. Проверяющему нужны оба поля — в проекциях `banExpires`
 * обязан ехать вместе с `banned`.
 *
 * Флаг в документе при этом снимает `liftExpiredBans()` по расписанию:
 * запросы к спискам, рассылке и табло фильтруют по `{ banned: { $ne: true } }`
 * и про срок не знают. Без снятия человек после срока входил бы, но в списках
 * и в рассылке оставался бы отключённым до первого входа — а клиенты входят
 * редко, письма же им идут постоянно.
 */

/** Отключение действует: флаг стоит, и срок либо не задан, либо не вышел. */
const isBanned = (user) =>
  Boolean(user?.banned) &&
  !(user.banExpires && new Date(user.banExpires).getTime() <= Date.now());

/**
 * Снять отключения с вышедшим сроком. Идемпотентно; условие стоит в самом
 * запросе, поэтому гонка с ручным включением безвредна.
 *
 * @returns {Promise<number>} сколько учётных записей включено
 */
const liftExpiredBans = async () => {
  const { modifiedCount } = await User.updateMany(
    { banned: true, banExpires: { $lte: new Date() } },
    { $set: { banned: false }, $unset: { banReason: "", banExpires: "" } },
  );
  return modifiedCount;
};

module.exports = { isBanned, liftExpiredBans };
