// node --test services/mcp/maskText.test.js
const { test } = require("node:test");
const assert = require("node:assert/strict");
const vm = require("node:vm");

const { maskText, maskEmails } = require("./maskText");

const HANG_MS = 3000;

// Прежние регулярки и циклы разбора на враждебных входах думали секунды и минуты, а
// { timeout } у node:test синхронный код не прерывает (проверено на Node 22 и 24).
// vm-таймаут V8 прерывает и регулярку на середине разбора: регресс роняет тест за
// hangMs, а не вешает прогон.
// Время меряем процессорное (process.cpuUsage), а не стенными часами: под нагрузкой
// процесс вытесняют, и стенные часы давали ложные падения. vm-таймаут остаётся по
// стенным часам — это страховка от зависания, а не измерение.
const timed = (label, run, hangMs = HANG_MS) => {
  let ms = 0;
  const measure = () => {
    const cpuBefore = process.cpuUsage();
    run();
    const cpu = process.cpuUsage(cpuBefore);
    ms = (cpu.user + cpu.system) / 1000;
  };
  try {
    vm.runInNewContext("measure()", { measure }, { timeout: hangMs });
  } catch (error) {
    if (error?.code !== "ERR_SCRIPT_EXECUTION_TIMEOUT") throw error;
    assert.fail(`${label}: не уложился в ${hangMs} мс — разбор перестал быть линейным`);
  }
  return ms;
};

