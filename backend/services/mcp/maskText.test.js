// node --test services/mcp/maskText.test.js
const { test } = require("node:test");
const assert = require("node:assert/strict");

const { maskText } = require("./maskText");

// Что считается телефоном — зафиксировано таблицей: маскируем контакты в
// подписях и «Кто звонил», но не даты, время, IP, версии, номера заявок,
// серийники, суммы и ИНН.

const MASKED = [
  ["+7 999 123-45-67", "[телефон]"],
  ["8 (423) 222-29-99", "[телефон]"],
  ["89991234567", "[телефон]"],
  ["+7(423)2222999", "[телефон]"],
  ["(423) 222-29-99", "[телефон]"],
  ["9991234567", "[телефон]"],
  ["тел. 222-29-99", "тел. [телефон]"],
  ["+375 29 123-45-67", "[телефон]"],
  ["Звоните: 8-999-123-45-67, 8-999-765-43-21", "Звоните: [телефон], [телефон]"],
  ["Кто звонил: +7 924 555 12 34", "Кто звонил: [телефон]"],
  ["заявка от 2026-09-17 89991234567", "заявка от 2026-09-17 [телефон]"],
  ["пишите ivan.petrov@corp.example.ru", "пишите [e-mail]"],
  ["пароль: Kap2022#", "пароль: [секрет скрыт]"],
  // Телефон в конце предложения и в скобках: точка и «(» рядом с номером не
  // должны отменять маску (финальное ревью: 6% телефонов утекали именно так).
  ["Мой номер 89991234567.", "Мой номер [телефон]."],
  ["Звоните 8 999 123-45-67.", "Звоните [телефон]."],
  ["+7 999 123 45 67.", "[телефон]."],
  ["моб. 8(999)1234567.", "моб. [телефон]."],
  ["Тел.+79991234567", "Тел.[телефон]"],
  ["(+79991234567)", "([телефон])"],
  // Номер по цифре через пробел после лишнего числа: окно перебора обязано
  // дотянуться до 11 групп (MAX_PHONE_GROUPS).
  ["12 8 9 9 9 1 2 3 4 5 6 7", "12 [телефон]"],
];

const UNCHANGED = [
  "IP 192.168.10.5, шлюз 10.0.0.1",
  "17.09.2026 10:00",
  "2026-09-17",
  "заявка № 51702",
  "SN VNB3K12345, S/N 1234567890",
  "RouterOS 7.15.3",
  "стоимость 1 500 000 руб",
  "ИНН 7701234567",
  "MAC 00-1A-2B-3C-4D-5E",
  "порт 8080, VLAN 100",
  "с 09:00-18:00",
  "годы 2024 2025 2026",
  "карта 4276 1234 5678 9012",
  "S/N89991234567",
  "артикул AB89991234567",
  // Защитные случаи ослабленных границ: точка перед номером (IP, версия,
  // дробь) и скобки вокруг номера заявки или инвентарного номера.
  "192.168.1.100",
  "10.0.50.70",
  "RouterOS 7.21.5 (long-term)",
  "17.09.2026",
  "2026-09-17",
  "s/n HCX089YGYCX",
  "1.9991234567",
  "заявка (51702)",
  "инв. (000123456789)",
];

test("contacts and secrets are masked", () => {
  for (const [input, expected] of MASKED) {
    assert.equal(maskText(input), expected, input);
  }
});

test("technical numbers stay as written", () => {
  for (const input of UNCHANGED) {
    assert.equal(maskText(input), input, input);
  }
});

test("empty values become an empty string", () => {
  assert.equal(maskText(null), "");
  assert.equal(maskText(undefined), "");
  assert.equal(maskText(51702), "51702");
});

// Регресс: список коротких чисел через пробел (например, серийники/счётчики в
// комментарии) не должен ни маскироваться, ни блокировать event loop — окно
// перебора в maskCandidate обязано быть ограничено числом цифр, а не расти как
// O(n) от количества групп на каждый старт (что в сумме давало кубическую
// сложность). Размер строки — у верхней границы лимита комментария (4000 симв.).
// Третий случай — группы вообще без цифр («1 - - - … - 2»): цифровая граница
// тут не срабатывает (цифр в окне почти нет), поэтому нужна отдельная граница
// по числу групп.
test("long whitespace-separated digit runs stay fast and unchanged", () => {
  const many = "1 2 3 4 ".repeat(500);
  const withTrailingLetter = `${many}x`;
  const digitFreeGroups = `1 ${"- ".repeat(2000)}2`;

  for (const input of [many, withTrailingLetter, digitFreeGroups]) {
    const start = Date.now();
    const result = maskText(input);
    const elapsed = Date.now() - start;
    assert.equal(result, input);
    assert.ok(elapsed < 1000, `expected under 1000ms, took ${elapsed}ms`);
  }
});
