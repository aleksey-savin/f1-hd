// Прежняя регулярка — эталон: на коротких строках она быстрая, и maskEmails обязан
// отвечать так же на любой строке, а не только на привычном тексте
const LEGACY_EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g;

test("maskEmails: на любой строке отвечает как прежняя регулярка", () => {
  // Куски, из которых собираются строки: знаки адреса, «@», зоны, разделители и
  // кириллица. Символы заданы кодами, без экранирований в исходнике
  const code = (value) => String.fromCharCode(value);
  const pieces = [
    "a", "b", "Z", "0", "9", ".", ".", "-", "-", "_", "%", "+", "@", "@", "@",
    "com", "ru", "co", "рф", "c", ".com", ".ru", ".c", "..", "-b", "b-",
    " ", "\n", "\t", ",", ";", ":", "/", "<", ">", "(", ")", '"', "=", "?",
    "ivan@corp.ru", "a@b.c", "a@b.com.au", "user:pass@host.example.com", "https://", "mailto:", "@/", "@param",
    "Привет", "иван", code(0xa0), code(0x3000), code(0x131), code(0x17f), code(0x212a),
  ];
  // Детерминированный генератор (mulberry32): тест повторяем, а не случаен
  let state = 20261001;
  const next = () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };

  let masked = 0;
  for (let i = 0; i < 20000; i += 1) {
    let sample = "";
    const parts = 1 + Math.floor(next() * 24);
    for (let k = 0; k < parts; k += 1) sample += pieces[Math.floor(next() * pieces.length)];
    const expected = sample.replace(LEGACY_EMAIL, "[e-mail]");
    if (expected !== sample) masked += 1;
    assert.equal(maskEmails(sample), expected, JSON.stringify(sample));
  }
  // Выборка не вырождена: в ней есть и строки с адресом, и без
  assert.ok(masked > 2000 && masked < 18000, `строк с адресом: ${masked}`);
});

// ── Маска e-mail: линейное время ───────────────────────────────────────────

// Прежняя `[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}` от каждой буквы серии
// заново искала «@» до конца серии: сто тысяч букв без «@» — 8 с, 262 144 — больше
// 20 с. Текст заявки приходит от кого угодно (дамп, токен, склеенная строка), а
// маска идёт по всему тексту до обрезки ответа
test("maskText: сто килобайт букв и знаков адреса без «@» маскируются за линейное время", { timeout: 5000 }, () => {
  const size = 100 * 1024;
  const shapes = {
    "буквы без «@»": "a".repeat(size),
    "буквы и «@» в конце": `${"a".repeat(size)}@`,
    "знаки локальной части без «@»": "a.b-c_d%e+f".repeat(Math.floor(size / 11)),
    "кириллица, затем серия букв": `Привет, ${"a".repeat(size)}`,
    "«@» и домен без точки": `a@${"b".repeat(size)}`,
    "«@» и домен из «.c»": `a@b${".c".repeat(size / 2)}`,
    "«a@» ×N": "a@".repeat(size / 2),
  };
  for (const [label, text] of Object.entries(shapes)) {
    const ms = timed(label, () => maskText(text));
    assert.ok(ms < 500, `${label}: ${ms.toFixed(1)} мс`);
  }
});
