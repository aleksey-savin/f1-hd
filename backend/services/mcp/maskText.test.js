// ── Маска телефона: линейное время ─────────────────────────────────────────

// Кандидат в телефон — вся серия цифровых групп разом. Прежний maskCandidate на
// каждой группе до 13 раз собирал строку окна (slice + join) и гонял по ней isPhone с
// replace и тремя regex: «1 » ×N — 4,5 с на мегабайт (4,3 мкс на знак), в 45 раз выше
// планки 100 мс/МБ, хотя цикл линеен и ограничен 13 группами. А текст заявки (до
// 10 МБ) маскируется целиком до обрезки ответа. Теперь окно решается по числу цифр,
// первой цифре и первой группе, без сборки строки. Предел зависания здесь больше (10 с):
// под нагрузкой стенные часы растут. Планка по процессору — 3 с: честный разбор
// мегабайта стоит 0,3–0,7 с, а первая форма в прогоне (холодная: растёт куча V8, и
// это системное время страниц) под нагрузкой — до 1,2 с; прежний цикл стоит
// 4,4–5,3 с и планку не проходит
test("maskText: мегабайт цифровых групп маскируется за линейное время", { timeout: 5000 }, () => {
  const MB = 1024 * 1024;
  const shapes = {
    "«1 » ×N": "1 ".repeat(MB / 2),
    "«(1 » ×N": "(1 ".repeat(Math.floor(MB / 3)),
    "«1 » ×N и «a» в конце": `${"1 ".repeat(MB / 2 - 1)}a`,
  };
  for (const [label, text] of Object.entries(shapes)) {
    const ms = timed(label, () => maskText(text), 10000);
    assert.ok(ms < 3000, `${label}: ${ms.toFixed(1)} мс`);
  }
});

