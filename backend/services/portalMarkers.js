/**
 * Пометки, которыми сам портал заменяет секреты и контакты в ответах ИИ-агенту,
 * и копия текста без них — для поиска секретов в том, что агент записал.
 *
 * Обычный источник заметки агента — конфигурация, прочитанная через MCP портала:
 * в ней стоит password=[скрыто], и такой фрагмент должен сохраняться. Копию без
 * пометок видят и инструменты записи (mcp/knowledgeWriteTools.js), и каждый скан
 * сохранённой заметки агента (secretsScanner.js#scanNote): иначе инструмент
 * принимал бы то, что пересчёт перед сохранением тут же помечает секретом.
 *
 * Модуль — лист: ничего не подключает. secretsScanner.js подключается из
 * mikrotik/configRedact.js и mcp/maskText.js, поэтому взять константы оттуда
 * нельзя (круг). Строки повторены литералами; что они совпадают с настоящими,
 * проверяет portalMarkers.test.js. Откуда строки:
 *   «[секрет скрыт]» — SECRET в mikrotik/configRedact.js, он же REDACTED в secretsScanner.js;
 *   «[скрыто]», «[скрипт скрыт: N строк]», «[строка скрыта: …]» — mikrotik/configRedact.js;
 *   «[скрипт скрыт]», «[вывод скрипта скрыт]» — mikrotik/liveState.js;
 *   «[телефон]», «[e-mail]» — mcp/maskText.js.
 */
const MARKER_LITERALS = [
  "[секрет скрыт]",
  "[скрыто]",
  "[скрипт скрыт]",
  "[вывод скрипта скрыт]",
  "[строка скрыта: не удалось разобрать]",
  "[телефон]",
  "[e-mail]",
];

// Одна регулярка из литералов (число строк — не длиннее шести цифр): линейно.
const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const MARKERS = new RegExp([...MARKER_LITERALS.map(escapeRegExp), "\\[скрипт скрыт: \\d{1,6} строк\\]"].join("|"), "g");

const EMPTY_VALUE = '""';
const SPACE = /\s/;

// Чем заменить пометку, решает знак сразу за ней:
//  - конец текста или пробельный знак — пустое значение в кавычках. Пустота здесь
//    не годится: после «password=» в конце строки правило сканера generic-api-key
//    перешагивает перевод строки (и пробел) и принимает за значение то, что дальше
//    («/interface…», «comment=»);
//  - любой другой знак — пустота: то, что приклеено к пометке, встаёт на место
//    значения и проверяется как значение («password: [скрыто]R00tP@ss» →
//    «password: R00tP@ss»). Кавычки здесь прятали приклеенное от правила сканера,
//    а «user:""@host» читалось как пароль в адресе.
// Проход один: пометка, сложившаяся из кусков после замены, остаётся в копии
// текстом и проверяется как любой другой текст.
const withoutMarkers = (text) =>
  typeof text === "string"
    ? text.replace(MARKERS, (marker, offset, whole) => {
        const next = whole[offset + marker.length];
        return next === undefined || SPACE.test(next) ? EMPTY_VALUE : "";
      })
    : text;

module.exports = { withoutMarkers, MARKER_LITERALS };
