/**
 * Сборка текстов telegram-уведомлений.
 *
 * До этого двадцать шаблонов лежали строками прямо в `middleware/notifications`,
 * причём девять из них — дословными дублями (один текст на три вида получателей).
 * Правка формата означала двадцать одинаковых правок, и они разъезжались.
 *
 * ПРАВИЛА, из которых собран каждый текст (согласовано макетом):
 *
 * 1. Первая строка всегда `<эмодзи> <b>что произошло</b> · #ticket_N`. Хештег
 *    виден сразу и тапается, не дожидаясь конца сообщения; номер больше нигде
 *    не повторяется.
 * 2. Жирным — ОДНО на сообщение: тема заявки. Плюс изменившееся значение там,
 *    где событие про изменение. Раньше жирным было набрано до пяти строк из
 *    шести, то есть не выделено ничего.
 * 3. Текст, написанный ЧЕЛОВЕКОМ, — всегда цитата: комментарий, причина
 *    возврата, закрывающий комментарий, отказ. Это и отличает комментарий от
 *    записи о событии на скорости пролистывания, ещё до чтения.
 * 4. Подписи «Тема:», «Компания:», «Инициатор:» убраны — значения узнаются без
 *    них. Подпись остаётся там, где без неё неоднозначно (срок, исполнитель).
 *
 * Приглушённого текста в Telegram НЕТ: разметка знает только жирный, курсив,
 * моноширинный, спойлер и цитату. Поэтому иерархия строится на «жирное против
 * обычного», а не на оттенках серого.
 */

/**
 * Экранирование обязательно и не обсуждается.
 *
 * Тема заявки, комментарий и имена приходят от людей и уходят в HTML. Один
 * символ `<` в теме — и Telegram отбивает СООБЩЕНИЕ ЦЕЛИКОМ: уведомление не
 * доходит вовсе, а в журнале остаётся только «can't parse entities». Раньше
 * подстановка шла сырой.
 */
const escapeHtml = (value) =>
  String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");

/**
 * Порог сворачивания цитаты. Три-четыре строки читаются на месте; переписка на
 * десять реплик не должна занимать экран, поэтому длинное Telegram сворачивает
 * сам (`expandable`, Bot API 7.4) и показывает «Развернуть».
 */
const QUOTE_EXPAND_AT = 200;

/** Речь человека. Пустой текст цитаты не даёт — пустая полоса выглядит сбоем. */
const quote = (text) => {
  const clean = escapeHtml(text).trim();
  if (!clean) return null;
  return `<blockquote${clean.length > QUOTE_EXPAND_AT ? " expandable" : ""}>${clean}</blockquote>`;
};

/** «Фамилия Имя», без двойных пробелов, если одного из полей нет. */
const personName = (person) =>
  `${person?.lastName || ""} ${person?.firstName || ""}`.trim();

/** «ООО «Ромашка» · Иванова Мария» — контекст одной строкой. */
const contextLine = (ticket) =>
  [ticket?.company?.alias, personName(ticket?.applicantId)]
    .filter(Boolean)
    .map(escapeHtml)
    .join(" · ") || null;

/**
 * Уведомление о событии заявки.
 *
 * @param {object}   args
 * @param {string}   args.emoji   значок события
 * @param {string}   args.event   что произошло, в первой строке
 * @param {object}   args.ticket  заявка (нужны num и title)
 * @param {string}   [args.quoted] текст человека — уйдёт в цитату
 * @param {string[]} [args.lines]  дополнительные строки (уже экранированные)
 */
const ticketEvent = ({ emoji, event, ticket, quoted, lines = [] }) => {
  const parts = [
    `${emoji} <b>${escapeHtml(event)}</b> · #ticket_${ticket.num}`,
    `<b>${escapeHtml(ticket.title)}</b>`,
  ];

  // Цитата идёт сразу за темой: это самое важное в сообщении после неё.
  const quoteBlock = quote(quoted);
  if (quoteBlock) parts.push(quoteBlock);

  parts.push(...lines.filter(Boolean));

  return parts.join("\n");
};

/**
 * Уведомление о комментарии — СВОЯ форма, и в этом весь смысл.
 *
 * Начинается с человека, а не со служебного «Комментарий к заявке N», и почти
 * целиком состоит из цитаты. Тема заявки уходит вниз контекстом: получатель уже
 * знает, о чём заявка, ему важно, что именно написали.
 */
const commentEvent = ({ comment, ticket }) => {
  const parts = [
    `💬 <b>${escapeHtml(personName(comment.createdBy))}</b> · #ticket_${ticket.num}`,
  ];

  const quoteBlock = quote(comment.content);
  if (quoteBlock) parts.push(quoteBlock);

  parts.push(escapeHtml(ticket.title));

  return parts.join("\n");
};

/**
 * Уведомление о запланированных работах — единственное, что относится сразу к
 * НЕСКОЛЬКИМ заявкам, поэтому хештегов в первой строке столько же.
 *
 * Прежняя версия собирала их так: `${tickets.map((t) => t + " ")}` — то есть
 * подставляла в строку МАССИВ, а он склеивается запятыми. В чат уходило
 * «#ticket_51713 ,#ticket_51714» с лишней запятой; то же самое было и в
 * перечислении номеров.
 */
const worksEvent = ({ emoji, event, tickets, lines = [] }) =>
  [
    `${emoji} <b>${escapeHtml(event)}</b> · ${tickets
      .map((num) => `#ticket_${num}`)
      .join(" ")}`,
    ...lines.filter(Boolean),
  ].join("\n");

/* ========================================================================
 * Rich Messages (Bot API 10.1+) — основная форма сообщений.
 *
 * Обычная HTML-разметка Telegram знает только начертания: жирный, курсив,
 * моноширинный, спойлер, цитата. Иерархию на них не построить — в живом чате
 * «жирная тема против обычного контекста» не считывается, что и показала
 * проверка на стенде. У рич-сообщений есть НАСТОЯЩАЯ структура: заголовок
 * своего кегля, таблица с колонками, разделитель, подвал.
 *
 * Блоки собираются объектами, а не HTML-строкой: форма описана в типах
 * `@grammyjs/types`, то есть проверяется компилятором на стороне отправщика, и
 * гадать про поддерживаемые теги не нужно.
 *
 * HTML-текст при этом ПРОДОЛЖАЕТ строиться и хранится рядом: если рич-формат
 * где-то не пройдёт, отправщик уходит на обычное сообщение, и уведомление не
 * теряется. Формату два месяца, подстраховка дешевле разбирательства.
 * ===================================================================== */

/** Жирный кусок текста. */
const richBold = (text) => ({ type: "bold", text: String(text) });

/** Ячейка таблицы. `align`/`valign` обязательны — в типе они не опциональны. */
const cell = (text, { header = false, align = "left" } = {}) => ({
  text,
  ...(header ? { is_header: true } : {}),
  align,
  valign: "top",
});

/**
 * Срок строкой таблицы. Живёт здесь, а не у места вызова: форматирование срока
 * иначе разъедется между уведомлением о новой заявке и уведомлением о переносе.
 */
const deadlineRow = (ticket, timezone) => [
  "Срок",
  ticket.deadline
    ? new Date(ticket.deadline).toLocaleDateString("ru", {
        timeZone: timezone,
        month: "long",
        day: "numeric",
        hour: "2-digit",
        minute: "2-digit",
      })
    : "не задан",
];

/** Пара «подпись — значение»; пустые значения строкой не становятся. */
const table = (rows) => {
  const filled = rows.filter(Boolean).filter(([, value]) => value);
  if (filled.length === 0) return null;
  return {
    type: "table",
    // С РАМКАМИ. Без флага Telegram рисует только вертикальный разделитель
    // колонок: строки расползаются по высоте и перестают читаться как ряды —
    // видно при сравнении двух сообщений подряд.
    is_bordered: true,
    // Подпись жирная: левая колонка — это подписи, и на них глаз не должен
    // задерживаться дольше, чем нужно, чтобы найти нужную строку.
    // `is_header` даёт ячейке фон, но начертание не меняет — поэтому жирный
    // ставится явно.
    cells: filled.map(([label, value]) => [
      cell(richBold(label), { header: true }),
      cell(String(value)),
    ]),
  };
};

/**
 * Первая строка — ОБЫЧНЫЙ ТЕКСТ, а не блок `heading`.
 *
 * Заголовочный блок даёт свой кегль и в ленте чата читается как крик: сообщение
 * начинает выглядеть объявлением, а не уведомлением. Крупным здесь быть нечему —
 * выделяется тема заявки строкой ниже, и этого достаточно.
 *
 * Номер идёт обычным текстом, БЕЗ решётки: хештег Telegram красит в синий, и
 * первая строка получалась двухцветной. Сам хештег стал строкой таблицы, где он
 * выглядит значением среди значений и так же тапается.
 */
const richHeading = (emoji, event, num) => ({
  type: "paragraph",
  text: `${emoji} ${event} · ${num}`,
});

/**
 * Хештег — ПОДВАЛОМ, отдельным блоком под таблицей.
 *
 * В таблице он был чужим: там значения заявки, а это служебная метка для
 * поиска по истории, и подпись «Хэштег» ничего не объясняла. Подвал — ровно то
 * место, где такому и положено быть.
 */
const hashtagFooter = (num) => ({
  type: "footer",
  text: `#ticket_${num}`,
});

/**
 * Цитата: блок из блоков, поэтому текст заворачивается в параграф.
 *
 * `credit` — штатное поле блока «кто это сказал». Автор принадлежит цитате, а
 * не строке события: в первой строке стоит вид сообщения, и подписывать её
 * фамилией значило бы называть человека раньше, чем то, что он сделал.
 */
const richQuote = (text, credit) => {
  const clean = String(text ?? "").trim();
  if (!clean) return null;
  return {
    type: "blockquote",
    blocks: [{ type: "paragraph", text: clean }],
    ...(credit ? { credit: String(credit) } : {}),
  };
};

/**
 * Событие заявки в виде блоков.
 *
 * Состояние заявки НЕ показывается: у новой оно всегда «Новая», а у остальных
 * событий его называет сам заголовок («Принята в работу», «Закрыта»).
 */
const ticketBlocks = ({ emoji, event, ticket, quoted, quotedBy, rows = [] }) =>
  [
    richHeading(emoji, event, ticket.num),
    // Тема — единственное жирное в сообщении: ради неё его и открывают.
    { type: "paragraph", text: richBold(ticket.title) },
    richQuote(quoted, quotedBy),
    table([
      ["Компания", ticket.company?.alias],
      ["Инициатор", personName(ticket.applicantId)],
      ...rows,
      ["Статус", ticket.state],
    ]),
    hashtagFooter(ticket.num),
  ].filter(Boolean);

/**
 * Комментарий: человек в заголовке, речь цитатой сразу под ним.
 *
 * Таблица та же, что у событий заявки, — иначе хештег пришлось бы селить в
 * подвал, и одно и то же значение жило бы в двух разных местах в зависимости от
 * вида сообщения. Тема заявки здесь строка таблицы: получатель уже знает, о чём
 * заявка, ему важно, что написали.
 */
const commentBlocks = ({ comment, ticket }) =>
  [
    richHeading("💬", "Комментарий", ticket.num),
    richQuote(comment.content, personName(comment.createdBy)),
    /**
     * Тема — ОДНА колонка, без подписи и без выделения.
     *
     * Подпись «Заявка» здесь ничего не добавляла: в сообщении о комментарии
     * второй строки, кроме темы заявки, и не бывает, а заголовочная ячейка
     * съедала треть ширины под слово и красила его фоном. Осталась рамка,
     * которая отделяет контекст от речи, — и всё.
     */
    { type: "table", is_bordered: true, cells: [[cell(ticket.title)]] },
    hashtagFooter(ticket.num),
  ].filter(Boolean);

/** Работы: заявок несколько, поэтому хештеги перечисляются в подвале. */
const worksBlocks = ({ emoji, event, tickets, rows = [] }) =>
  [
    { type: "heading", size: 3, text: `${emoji} ${event}` },
    table(rows),
    { type: "divider" },
    {
      type: "footer",
      text: tickets.map((num) => `#ticket_${num}`).join(" "),
    },
  ].filter(Boolean);

module.exports = {
  escapeHtml,
  quote,
  personName,
  contextLine,
  ticketEvent,
  commentEvent,
  worksEvent,
  ticketBlocks,
  commentBlocks,
  worksBlocks,
  deadlineRow,
  table,
  QUOTE_EXPAND_AT,
};
