const { AppError } = require("./errorHandling");

/**
 * Жёсткая проверка: без опознанного пользователя дальше не пускает. Точная
 * замена прежнего `isAuth`, только личность уже установлена `attachSession`, а
 * не поднимается заново.
 *
 * Статус 401 сохраняется дословно: форма входа показывает инлайн только
 * сообщения со статусами из своего списка (`INLINE_STATUSES` во фронтенде), а
 * корневой загрузчик по 401 уводит на страницу входа. Любой другой код здесь
 * уронил бы error boundary вместо редиректа.
 */
module.exports = (req, res, next) => {
  if (!req.auth) {
    // Легаси-флаг: его читают логгер и обработчик ошибок.
    req.isAuth = false;
    return next(
      new AppError("Для обработки запроса требуется авторизация.", 401),
    );
  }
  next();
};
