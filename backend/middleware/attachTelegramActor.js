const { AppError } = require("./errorHandling");
const { resolveActor } = require("@/services/telegramActor");

/**
 * Кто стоит за запросом бота.
 *
 * `isTelegramBot` доказывает, что зовёт бот, и на этом его работа кончается.
 * Дальше нужен АКТОР — человек, от чьего имени выполняется действие: все
 * контроллеры берут его из `req.auth` (`getAuthData`, `req.userId`, `can()`),
 * и без него написанное для браузера не работает. Именно поэтому ручка
 * создания заявки из телеграма когда-то была закомментирована, а бот пошёл
 * писать в Mongo напрямую.
 *
 * Ставится ПОСЛЕ `isTelegramBot` и заменяет собой `attachSession`, который на
 * этих маршрутах ничего не находит. `req.auth` получается той же сборкой
 * (`services/authContext`), что и у браузерного сеанса, — отличается только
 * `session`, которого у бота нет.
 *
 * Заголовок, а не query: идентификатор актора — не секрет, но строка запроса
 * целиком уходит в `access.log`, и складывать туда, кто чем занимался в боте,
 * незачем.
 */
const HEADER = "x-tg-actor";

module.exports = async (req, res, next) => {
  try {
    const actor = await resolveActor(req.get(HEADER));

    if (!actor) {
      /**
       * Один ответ на все причины: не привязан, отключён, компания отключена,
       * служебная учётка, один чат на двух учётках. Разбирать их наружу
       * означало бы отвечать боту (а через него — кому угодно, кто ему пишет)
       * на вопросы о чужих учётных записях.
       */
      return next(
        new AppError(
          "Telegram не привязан к учётной записи. Привяжите его в «Мой аккаунт»",
          401,
        ),
      );
    }

    req.auth = actor;
    req.userId = actor.userId;

    next();
  } catch (error) {
    next(error);
  }
};
