const router = require("express").Router();
const requireAuth = require("../../middleware/requireAuth");
const rateLimit = require("express-rate-limit");
const c = require("../../controllers/taxi");
const live = rateLimit({ windowMs: 60000, max: 30, keyGenerator: (req) => String(req.auth.userId), standardHeaders: true, legacyHeaders: false });
router.use(requireAuth);
router.get("/settings", c.settings);
router.put("/settings", live, c.saveSettings);
router.post("/check", live, c.check);
router.post("/sync", live, c.sync);
router.put("/employees/:externalId", live, c.mapEmployee);
router.get("/trips", c.list);
router.post("/candidates", c.candidates);
router.get("/tickets/:id/trips", c.ticketTrips);
router.get("/tickets/:id/candidates", c.ticketCandidates);
router.patch("/trips/:id/allocation", c.allocate);
router.get("/trips/:id/allocation-options", c.allocationOptions);
router.delete("/trips/:id", c.remove);
router.get("/trips/:id", c.detail);
module.exports = router;
